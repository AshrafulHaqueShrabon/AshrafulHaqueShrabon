"""Render the images the daily workflow publishes to the `output` branch."""

from __future__ import annotations

from pathlib import Path

from .config import Config
from .live.refresh import Source
from .sections import arcade, languages

THEMES = ("light", "dark")

BRANCH_README = """# output branch

Generated by the `live` workflow: do not edit. It is force-pushed on every run,
so this branch never accumulates history. The profile README embeds these
images through raw.githubusercontent.com URLs; `cache/live.json` holds the
last-known-good data used when an API is down.
"""


def game_files(arcade_dir: Path | None, game: str) -> dict[str, Path]:
    """Freshly generated game SVGs by theme (both generators write light + dark)."""
    if not arcade_dir:
        return {}
    names = ({"light": "snake.svg", "dark": "snake-dark.svg"} if game == "snake" else
             {"light": f"{game}-contribution-graph.svg", "dark": f"{game}-contribution-graph-dark.svg"})
    found = {t: arcade_dir / n for t, n in names.items()}
    return found if all(p.exists() and p.stat().st_size > 0 for p in found.values()) else {}


def arcade_files(cfg: Config, arcade_dir: Path | None, previous: Path | None, log=print) -> dict[str, str]:
    """Fresh game (recolored) → last-known-good → placeholder."""
    fresh = game_files(arcade_dir, cfg.arcade)
    if fresh:
        log("  [live]  arcade: new game")
        return {f"arcade-{t}.svg": arcade.recolor(p.read_text(encoding="utf-8"), cfg.accent, t)
                for t, p in fresh.items()}
    if previous and all((previous / f"arcade-{t}.svg").exists() for t in THEMES):
        log("  [cache] arcade: no new game this run; keeping the previous one")
        return {f"arcade-{t}.svg": (previous / f"arcade-{t}.svg").read_text(encoding="utf-8") for t in THEMES}
    log("  [none]  arcade: no game yet (placeholder shown)")
    return {f"arcade-{t}.svg": arcade.placeholder(t) for t in THEMES}


def render(cfg: Config, source: Source, *, arcade_dir: Path | None = None, previous: Path | None = None,
           log=print) -> dict[str, str]:
    items = languages.shares((source.data or {}).get("languages", []), cfg.top_languages, cfg.exclude_languages)
    files = {f"languages-{t}.svg": languages.render(items, t) for t in THEMES}
    if cfg.arcade:
        files.update(arcade_files(cfg, arcade_dir, previous, log))
    return files
